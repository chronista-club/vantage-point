//! Project Host — project の状態・進行・交通整理に責任を持つ決定的サービス（doc 44 D3 / §7）。
//!
//! ## 位置付け
//!
//! 旧 SP は "Project Host" を名乗るプロセス宿主で、project そのものを host していなかった。
//! P1 の fold-in でプロセスとしての SP が消えた今、この名は
//! **「project の面倒を見る決定的な執事」** として転生する。
//!
//! ## アーキテクチャ原則: Host は決定論。LLM にしない
//!
//! conductor の既知事故 2 件（wire ack 遅延による二重配送 / conductor session 固定化）は
//! 「帳簿と受付を LLM セッションに置いた」ことの帰結で、LLM Host は同じ問題を再生産する。
//! Host は 3 層で仕事を分ける:
//!
//! 1. **決定的判定**（Host 内・純関数 = calculations、テスト可能）— [`farewell::judge_farewell`]
//! 2. **LLM への発注**（stateless one-shot。進捗の文章化など言語タスクのみ）— 未実装
//! 3. **人間へのエスカレーション**（帳簿に積む）— [`farewell::FarewellVerdict::AskHuman`]
//!
//! 層 1 で決まらないものを層 3 に回すのが要で、**Host は推測しない**。
//!
//! ## 実装状況
//!
//! D3 の振る舞いインベントリのうち、第一号の**「見送り」だけ**が実装対象（P3 第一スライス）。
//! 判定基準が言語化済み・失敗の被害が小さい・毎週確実に価値が出る、が選定理由。
//!
//! | 振る舞い | 状態 |
